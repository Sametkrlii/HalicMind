-- HaliçMind catalog, PostgreSQL. Apply once to an empty database.
-- Single-university schema: every record belongs to Haliç University.
BEGIN;

CREATE TABLE academic_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key TEXT NOT NULL UNIQUE CHECK (length(trim(source_key)) > 0),
    name_tr TEXT NOT NULL CHECK (length(trim(name_tr)) > 0),
    name_en TEXT,
    unit_type TEXT NOT NULL CHECK (unit_type IN ('faculty','institute','school','vocational_school','other')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE programs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_unit_id BIGINT NOT NULL REFERENCES academic_units(id) ON DELETE RESTRICT,
    source_key TEXT NOT NULL UNIQUE CHECK (length(trim(source_key)) > 0),
    name_tr TEXT NOT NULL CHECK (length(trim(name_tr)) > 0),
    name_en TEXT,
    degree_level TEXT NOT NULL CHECK (degree_level IN ('associate','bachelor','master','doctorate','other')),
    language_code TEXT CHECK (language_code IN ('tr','en','mixed','other')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_programs_unit ON programs(academic_unit_id);

CREATE TABLE curricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id BIGINT NOT NULL REFERENCES programs(id) ON DELETE RESTRICT,
    source_key TEXT NOT NULL CHECK (length(trim(source_key)) > 0),
    label TEXT NOT NULL CHECK (length(trim(label)) > 0),
    entry_year SMALLINT CHECK (entry_year BETWEEN 1900 AND 2200),
    semester_count SMALLINT NOT NULL CHECK (semester_count BETWEEN 1 AND 24),
    source_url TEXT NOT NULL CHECK (source_url LIKE 'https://%' OR source_url LIKE 'http://%'),
    last_verified_at DATE NOT NULL,
    coverage_status TEXT NOT NULL DEFAULT 'partial' CHECK (coverage_status IN ('partial','complete','unavailable')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (program_id, source_key)
);

CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key TEXT NOT NULL UNIQUE CHECK (length(trim(source_key)) > 0),
    course_code TEXT NOT NULL CHECK (course_code = upper(trim(course_code)) AND length(course_code) > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_courses_code ON courses(course_code);

CREATE TABLE course_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE RESTRICT,
    revision_key TEXT NOT NULL CHECK (length(trim(revision_key)) > 0),
    name_tr TEXT,
    name_en TEXT,
    language_code TEXT CHECK (language_code IN ('tr','en','mixed','other')),
    ects NUMERIC(5,2) CHECK (ects >= 0 AND ects <= 120),
    local_credit NUMERIC(5,2) CHECK (local_credit >= 0 AND local_credit <= 120),
    source_url TEXT NOT NULL CHECK (source_url LIKE 'https://%' OR source_url LIKE 'http://%'),
    last_verified_at DATE NOT NULL,
    verification_status TEXT NOT NULL DEFAULT 'unverified' CHECK (verification_status IN ('unverified','verified','needs_review')),
    CHECK (length(trim(coalesce(name_tr,''))) > 0 OR length(trim(coalesce(name_en,''))) > 0),
    UNIQUE (course_id, revision_key)
);

CREATE TABLE elective_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id BIGINT NOT NULL REFERENCES curricula(id) ON DELETE RESTRICT,
    source_key TEXT NOT NULL CHECK (length(trim(source_key)) > 0),
    name TEXT NOT NULL CHECK (length(trim(name)) > 0),
    required_course_count SMALLINT CHECK (required_course_count >= 0),
    required_ects NUMERIC(5,2) CHECK (required_ects >= 0),
    UNIQUE (curriculum_id, source_key),
    UNIQUE (id, curriculum_id)
);

CREATE TABLE curriculum_courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curriculum_id BIGINT NOT NULL REFERENCES curricula(id) ON DELETE RESTRICT,
    course_revision_id BIGINT NOT NULL REFERENCES course_revisions(id) ON DELETE RESTRICT,
    semester SMALLINT NOT NULL CHECK (semester BETWEEN 1 AND 24),
    course_type TEXT NOT NULL CHECK (course_type IN ('required','elective')),
    elective_group_id BIGINT,
    FOREIGN KEY (elective_group_id, curriculum_id) REFERENCES elective_groups(id, curriculum_id) ON DELETE RESTRICT,
    CHECK (elective_group_id IS NULL OR course_type = 'elective'),
    UNIQUE (curriculum_id, semester, course_revision_id),
    UNIQUE (id, curriculum_id)
);
CREATE INDEX ix_curriculum_courses_browse ON curriculum_courses(curriculum_id, semester, course_type);
CREATE INDEX ix_curriculum_courses_revision ON curriculum_courses(course_revision_id);
CREATE INDEX ix_curriculum_courses_group ON curriculum_courses(elective_group_id, curriculum_id);

CREATE TABLE prerequisites (
    curriculum_course_id BIGINT NOT NULL,
    required_curriculum_course_id BIGINT NOT NULL,
    curriculum_id BIGINT NOT NULL,
    PRIMARY KEY (curriculum_course_id, required_curriculum_course_id),
    CHECK (curriculum_course_id <> required_curriculum_course_id),
    FOREIGN KEY (curriculum_course_id, curriculum_id) REFERENCES curriculum_courses(id, curriculum_id) ON DELETE RESTRICT,
    FOREIGN KEY (required_curriculum_course_id, curriculum_id) REFERENCES curriculum_courses(id, curriculum_id) ON DELETE RESTRICT
);
CREATE INDEX ix_prerequisites_required ON prerequisites(required_curriculum_course_id, curriculum_id);

CREATE TABLE prerequisite_notes (
    curriculum_course_id BIGINT PRIMARY KEY REFERENCES curriculum_courses(id) ON DELETE RESTRICT,
    official_text TEXT NOT NULL CHECK (length(trim(official_text)) > 0)
);

CREATE VIEW catalog_export AS
SELECT cc.id AS curriculum_course_id, 'Haliç University' AS university,
       au.name_en AS faculty, p.name_en AS department,
       au.unit_type, p.degree_level, cu.label AS curriculum,
       cu.entry_year, cc.semester, c.course_code,
       r.name_tr AS course_name_tr, r.name_en AS course_name_en,
       r.ects, r.local_credit, r.language_code, cc.course_type,
       eg.name AS elective_group, r.source_url, r.last_verified_at,
       r.verification_status, cu.coverage_status,
       (au.is_active AND p.is_active AND cu.is_active AND c.is_active) AS is_active
FROM curriculum_courses cc
JOIN curricula cu ON cu.id = cc.curriculum_id
JOIN programs p ON p.id = cu.program_id
JOIN academic_units au ON au.id = p.academic_unit_id
JOIN course_revisions r ON r.id = cc.course_revision_id
JOIN courses c ON c.id = r.course_id
LEFT JOIN elective_groups eg ON eg.id = cc.elective_group_id;

COMMIT;
